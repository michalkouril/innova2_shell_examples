"""Generate an Innova2 connectivity cfg for a Vitis_Accel_Examples example.

Our platform exposes exactly one usable large memory: sptag `bank0` (DDR4, 4 GB).
Stock example cfgs reference DDR[n]/HBM[n], which do not exist here, so every
kernel m_axi port has to be re-pinned. Ports are the pointer/array arguments of
each `extern "C"` top function; scalars and hls::stream refs are not m_axi.
"""
import re, sys, os, glob, json

# TASKS 585kk: the target memory is env-overridable so a kernel can be pinned somewhere OTHER than
# the DDR. That is the discriminator when a CU starts and never finishes: if the same kernel
# completes with its buffers in PLRAM (BRAM in the static region) but hangs on bank0, the fault is
# the DDR path, not the CU, the clock or the RP.
import os as _os
MEM = _os.environ.get("VMEM", "bank0")
# 2026-09-27: VMEM may be a list, e.g. "bank0,PLRAM2": port 0 of each kernel -> the first memory, every
# later port -> the last one. Used to build ONE xclbin that uses both DDR and PLRAM (rbdw write-error test).
# A single value behaves exactly as before.
MEMS = [m for m in MEM.split(",") if m]

def strip_comments(s):
    s = re.sub(r'/\*.*?\*/', ' ', s, flags=re.S)
    s = re.sub(r'//[^\n]*', ' ', s)
    return s

def kernels_in(path):
    """-> [(kernel_name, [port names])] for each extern "C" top function."""
    txt = strip_comments(open(path, errors='ignore').read())
    out = []
    for m in re.finditer(r'extern\s+"C"\s*\{(.*)$', txt, flags=re.S):
        body = m.group(1)
        fm = re.search(r'\bvoid\s+(\w+)\s*\(([^)]*)\)\s*\{', body, flags=re.S)
        if not fm:
            continue
        name, arglist = fm.group(1), fm.group(2)
        ports = []
        for a in arglist.split(','):
            a = a.strip()
            if not a or 'stream' in a:      # hls::stream& is AXIS, not m_axi
                continue
            if '*' in a or '[' in a:
                ident = re.findall(r'(\w+)\s*(?:\[[^\]]*\])?\s*$', a)
                if ident:
                    ports.append(ident[-1])
        out.append((name, ports))
        break                                # one top function per file
    return out

def main():
    exdir = sys.argv[1]
    # optional: restrict to one binary container's kernels (multi-xclbin examples)
    only = set(sys.argv[2].split(',')) if len(sys.argv) > 2 else None
    src = os.path.join(exdir, 'src')
    kern = {}
    for f in sorted(glob.glob(os.path.join(src, '*.cpp')) + glob.glob(os.path.join(src, '*.c'))):
        if os.path.basename(f) == 'host.cpp':
            continue
        for name, ports in kernels_in(f):
            if only is None or name in only:
                kern[name] = ports

    # Preserve any nk=/sc=/stream lines the example already declares; those name
    # the CUs and kernel-to-kernel links, which we are not changing.
    # Also harvest CU.port pairs straight from the example's own sp= lines: for
    # RTL kernels there is no extern "C" to parse, and the shipped cfg is the
    # authoritative list of m_axi ports. We keep the port, replace the memory.
    keep, cus, shipped = [], {}, []
    for c in sorted(glob.glob(os.path.join(exdir, '*.cfg'))):
        for ln in open(c, errors='ignore'):
            s = ln.strip()
            m = re.match(r'nk\s*=\s*(\w+)\s*:\s*(\d+)\s*(?::\s*(\S+))?', s)
            if m:
                k, n, names = m.group(1), int(m.group(2)), m.group(3)
                cus[k] = [x.strip() for x in names.split('.')] if names \
                         else ['%s_%d' % (k, i + 1) for i in range(n)]
                keep.append(s)
            elif s.startswith(('sc=', 'stream_connect')):
                keep.append(s)
            else:
                m = re.match(r'sp\s*=\s*(\w+)\.(\w+)\s*:', s)
                if m:
                    shipped.append((m.group(1), m.group(2)))
    for k in kern:
        cus.setdefault(k, ['%s_1' % k])

    lines = ['# generated by gen_cfg.py -- all m_axi ports pinned to %s' % MEM,
             '[connectivity]'] + keep
    pairs = []
    for k, ports in sorted(kern.items()):
        for cu in cus.get(k, []):
            for p in ports:
                pairs.append((cu, p))
    for cu, p in shipped:                     # RTL kernels land here
        if only is not None and not any(cu.startswith(k) for k in only):
            continue
        if (cu, p) not in pairs:
            pairs.append((cu, p))
    n = 0
    idx = {}
    for cu, p in pairs:
        k = idx.get(cu, 0); idx[cu] = k + 1
        lines.append('sp=%s.%s:%s' % (cu, p, MEMS[min(k, len(MEMS) - 1)]))
        n += 1
    if n == 0:
        sys.stderr.write('gen_cfg: NO m_axi ports found in %s -- refusing to emit a cfg\n' % exdir)
        sys.exit(3)
    print('\n'.join(lines))
    sys.stderr.write('gen_cfg: %d kernel(s), %d CU(s), %d sp lines\n'
                     % (len(kern), sum(len(v) for v in cus.values()), n))

if __name__ == '__main__':
    main()
