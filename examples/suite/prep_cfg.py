"""Prepare connectivity for one example, one cfg per binary container.

Our platform has a single large memory (sptag bank0); stock examples name
DDR[n]/HBM[n], which do not exist here, so every m_axi port is re-pinned.

Examples pass their own cfg through a per-container variable
(VPP_LDFLAGS_<container> += --config ./x.cfg). Adding a second --config makes
v++ see nk=/stream_connect= twice:
    60-696 Compute Unit with name 'vadd_1' already exists
    83-2202 --sc tag applied redundantly
So when a cfg is already referenced we rewrite THAT file; only when none is
referenced do we add one and point the link line at it.
"""
import re, sys, os, glob
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_cfg import kernels_in, MEM, MEMS

exdir = sys.argv[1]
mk = os.path.join(exdir, 'makefile_us_alveo.mk')
txt = open(mk).read()

vars_ = {}
for n, op, v in re.findall(r'^(\w+)\s*(:=|\+=|=)\s*(.*)$', txt, re.M):
    vars_[n] = (vars_.get(n, '') + ' ' + v) if op == '+=' else v
def expand(s, d=0):
    return s if d > 6 else re.sub(r'\$\((\w+)\)', lambda m: expand(vars_.get(m.group(1), ''), d+1), s)

# kernel name -> m_axi ports
kern = {}
for f in sorted(glob.glob(os.path.join(exdir, 'src', '*.cpp')) + glob.glob(os.path.join(exdir, 'src', '*.c'))):
    if os.path.basename(f) == 'host.cpp':
        continue
    for name, ports in kernels_in(f):
        kern[name] = ports

rules = re.findall(r'^\$\(BUILD_DIR\)/(\S+?)\.xclbin:\s*(.*)$', txt, re.M)
if not rules:
    print('  !! no xclbin rules found'); sys.exit(4)

lines = txt.split('\n')
wrote = 0
for cname, prereq in rules:
    xos = sorted(set(re.findall(r'([\w]+)\.xo', expand(prereq))))
    ks = [k for k in (xos or list(kern)) if k in kern] or list(kern)

    # does this container already reference a cfg?
    ref = re.search(r'VPP_LDFLAGS_%s\s*\+?=\s*.*?--config\s+\./(\S+\.cfg)' % re.escape(cname), txt)
    cfg = os.path.join(exdir, ref.group(1)) if ref else os.path.join(exdir, 'innova2_%s.cfg' % cname)

    keep, cus, shipped = [], {}, []
    if os.path.exists(cfg):
        for ln in open(cfg, errors='ignore'):
            s = ln.strip()
            m = re.match(r'nk\s*=\s*(\w+)\s*:\s*(\d+)\s*(?::\s*(\S+))?', s)
            if m:
                k, n, nm = m.group(1), int(m.group(2)), m.group(3)
                cus[k] = [x.strip() for x in nm.split('.')] if nm else ['%s_%d' % (k, i+1) for i in range(n)]
                keep.append(s)
            elif s.startswith(('sc=', 'stream_connect')):
                keep.append(s)
            elif re.match(r'sp\s*=\s*(\w+)\.(\w+)\s*:', s):
                m2 = re.match(r'sp\s*=\s*(\w+)\.(\w+)\s*:', s)
                shipped.append((m2.group(1), m2.group(2)))     # keep port, drop its memory
            elif s and not s.startswith(('[', '#')):
                keep.append(s)
    for k in ks:
        cus.setdefault(k, ['%s_1' % k])

    pairs = [(cu, p) for k in ks for cu in cus.get(k, []) for p in kern.get(k, [])]
    # RTL kernels: their memory arguments come from rtl_ports.map (no C source to parse); unpinned they fall to the
    # platform's default memory, which is HOST on route V
    _map = os.path.join(os.path.dirname(os.path.abspath(__file__)), "rtl_ports.map")
    if os.path.exists(_map):
        _ex = os.path.basename(os.path.abspath(exdir))
        for _ln in open(_map):
            _f = _ln.split("#")[0].split()
            if len(_f) == 2 and _f[0] == _ex and "." in _f[1]:
                _cu, _arg = _f[1].split(".", 1)
                if (_cu, _arg) not in pairs:
                    pairs.append((_cu, _arg))
    for cu, p in shipped:
        if (cu, p) not in pairs:
            pairs.append((cu, p))
    # VPROFILE (route V per-card DDR profile, 2026-10-08): every link of this build carries the card's profile in its
    # OWN cfg ([advanced] userPreSysLinkOverlayTcl = the profile file, which runs the platform hook) -- also containers
    # without m_axi ports: a route-V link without the hook would ship the template MIG.
    PROF = os.environ.get("VPROFILE", "")
    if not pairs and not PROF:
        print('  %-34s no m_axi ports -- leaving v++ default assignment' % cname)
        continue

    with open(cfg, 'w') as fh:
        fh.write('# generated by prep_cfg.py -- m_axi ports pinned to %s\n[connectivity]\n' % MEM)
        if PROF:
            fh.write('# per-card DDR profile (route V): %s\n' % os.path.basename(PROF))
        for s in keep:
            fh.write(s + '\n')
        _idx = {}     # VMEM list: port 0 of each CU -> first memory, later ports -> the last one
        # VMEM_MAP="port:mem,port:mem" pins named ports explicitly (a kernel's ports that share an HLS
        # bundle must share a memory -- one AXI interface cannot reach two segments).
        _vmap = dict(x.split(":", 1) for x in os.environ.get("VMEM_MAP", "").split(",") if ":" in x)
        for cu, p in pairs:
            k = _idx.get(cu, 0); _idx[cu] = k + 1
            mem = _vmap.get(p, MEMS[min(k, len(MEMS) - 1)])
            fh.write('sp=%s.%s:%s\n' % (cu, p, mem))
        if PROF:
            fh.write('[advanced]\nparam=compiler.userPreSysLinkOverlayTcl=%s\n' % PROF)
    print('  %-34s %-28s %d sp%s' % (cname, os.path.basename(cfg), len(pairs),
                                     ' (rewrote example cfg)' if ref else ' (new)'))
    wrote += 1

    if not ref:   # nothing passes this cfg yet -- point the link line at it
        head = '$(BUILD_DIR)/%s.xclbin:' % cname
        try:
            i = next(j for j, l in enumerate(lines) if l.startswith(head))
        except StopIteration:
            print('  !! no rule line for %s' % cname); sys.exit(4)
        k = i + 1
        while k < len(lines) and lines[k].strip() and not (not lines[k].startswith('\t') and ':' in lines[k]):
            k += 1
        flag = '--config $(PWD)/%s' % os.path.basename(cfg)
        blk, done = lines[i:k], False
        for j, l in enumerate(blk):
            if '$(VPP_LDFLAGS)' in l:
                # ADD the cfg next to VPP_LDFLAGS, never replace it: replacing silently dropped every flag vbuild.sh
                # passes in VPP_LDFLAGS (2026-10-08: kernel_chain's impl strategy never reached v++)
                blk[j] = l.replace('$(VPP_LDFLAGS)', '$(VPP_LDFLAGS) ' + flag); done = True; break
            if re.search(r'(v\+\+|\$\(VPP\))\s+-l\b', l):
                blk[j] = re.sub(r'((?:v\+\+|\$\(VPP\))\s+-l)', r'\1 ' + flag.replace('\\', '\\\\'), l, count=1)
                done = True; break
        if not done:
            print('  !! could not attach cfg to the link line for %s' % cname); sys.exit(4)
        lines[i:k] = blk

open(mk, 'w').write('\n'.join(lines))
print('  containers: %d, cfgs written: %d' % (len(rules), wrote))
